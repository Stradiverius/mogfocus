"""Rebuild the narrow, reviewed legacy mapping from a pinned ATT checkout.

This is deliberately not a general ATT parser. Boundaries limit extraction to
the original Retail MC/BWL item blocks and Tier 4 exchange costs. Review new
upstream revisions before changing the pinned SHA or the extraction bounds.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

PIN = "43801dcbd75637ab62aa141409404179d5130338"
root = Path(sys.argv[1])
assert subprocess.check_output(["git", "-C", str(root), "rev-parse", "HEAD"], text=True).strip() == PIN
base = root / ".contrib/.db/standard"
raids = base / "01 - Dungeons Raids"
records = {}

for file, instance, start, end in [
    ("01 - Classic/1.0 Molten Core.lua", 741, "\t\t\tn(ZONE_DROPS,", "\t\t\tapplyclassicphase(SOD_PHASE_FOUR, d("),
    ("01 - Classic/1.6 Blackwing Lair.lua", 742, "\t\t\te(1529,", "\t\t\tapplyclassicphase(SOD_PHASE_FIVE, d("),
]:
    text = (raids / file).read_text()
    text = text[text.index(start):text.index(end)]
    encounter = None
    for line in text.splitlines():
        match = re.match(r"\s*e\((\d+),\s*\{\s*--\s*(.+)", line)
        if match:
            encounter = int(match[1])
        item = re.match(r"\s*i\((\d+)[,)]", line)
        if item and 16795 <= int(item[1]) <= 16966:
            key = int(item[1])
            record = dict(instanceID=instance, encounterID=encounter, method="DIRECT" if encounter else "TRASH", size="LEGACY40", expansionID=0)
            records.setdefault(key, []).append(record)

tokens = {}
for file, instance in [("1 Karazhan (Raid).lua", 745), ("2 Gruul's Lair.lua", 746), ("3 Magtheridon's Lair.lua", 747)]:
    encounter = None
    for line in (raids / "02 - Burning Crusade" / file).read_text().splitlines():
        match = re.match(r"\s*e\((\d+),", line)
        if match: encounter = int(match[1])
        item = re.match(r"\s*i\((297\d\d),", line)
        if item and 29753 <= int(item[1]) <= 29767:
            tokens[int(item[1])] = dict(instanceID=instance, encounterID=encounter, method="TOKEN", size="LEGACY10" if instance == 745 else "LEGACY25", expansionID=1)

text = (base / "02 - Outdoor Zones/03 Outland/1 - Shattrath City.lua").read_text().split("local TIER_FIVE_GROUPS")[0]
for item, token in re.findall(r'i\((\d+),\s*\{[^\n]*\n\s*cost = \{ \{ "i", (\d+), 1 \} \}', text):
    record = dict(tokens[int(token)], tokenID=int(token), vendorKey="VENDORS_T4")
    records[int(item)] = [record]
assert len(tokens) == 15
assert len(records) == 229, len(records)

def lua(value):
    if value is None: return "nil"
    if isinstance(value, str): return json.dumps(value, ensure_ascii=False)
    if isinstance(value, int): return str(value)
    if isinstance(value, list): return "{ " + ", ".join(map(lua, value)) + " }"
    return "{ " + ", ".join(k + " = " + lua(v) for k, v in value.items()) + " }"

lines = ["-- Generated by tools/import_sources.py; ATT MIT attribution in LICENSES/ATT.txt.", "local _, M = ...", "M.SourceData = {", '    verifiedBuild = "12.1.5.70529",', f'    reference = "ATT {PIN}",', "    items = {"]
for key, record in sorted(records.items()):
    lines.append(f"        [{key}] = {lua(record)},")
lines += ["    },", "}", ""]
Path(__file__).resolve().parents[1].joinpath("MogFocus/Data/Sources.lua").write_text("\n".join(lines))
print(f"Generated {len(records)} item mappings")
