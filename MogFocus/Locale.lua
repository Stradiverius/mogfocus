function M.L(key, ...)
    local lang = M.Store and M.Store.settings and M.Store.settings.language or "cs"
    local dict = M.locales[lang] or M.locales.en
    local text = dict[key] or M.locales.en[key] or key
    if select("#", ...) > 0 then return string.format(text, ...) end
    return text
end
